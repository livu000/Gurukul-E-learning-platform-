const crypto = require('crypto');
const { Certificate, Course, Enrollment, User } = require('../models');
const { buildSimplePdf } = require('../utils/document.util');

function buildCertificatePayload(certificate) {
  return {
    id: certificate.id,
    certificateUid: certificate.certificateUid,
    verificationCode: certificate.verificationCode,
    certificateUrl: certificate.certificateUrl,
    issuedAt: certificate.issuedAt,
    isValid: certificate.isValid,
    userId: certificate.userId,
    courseId: certificate.courseId,
    enrollmentId: certificate.enrollmentId,
    userNameSnapshot: certificate.userNameSnapshot,
    courseTitleSnapshot: certificate.courseTitleSnapshot
  };
}

function buildCertificatePdf(certificate) {
  const learnerName = certificate.userNameSnapshot || certificate.user?.name || 'Student';
  const courseTitle = certificate.courseTitleSnapshot || certificate.course?.title || 'Course';
  const issueDate = new Date(certificate.issuedAt).toLocaleDateString('en-IN', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  return buildSimplePdf({
    title: 'Gurukul Certificate of Completion',
    lines: [
      `Awarded to: ${learnerName}`,
      `Course: ${courseTitle}`,
      `Issued on: ${issueDate}`,
      `Certificate UID: ${certificate.certificateUid}`,
      `Verification Code: ${certificate.verificationCode}`,
      'This certificate is generated by the Gurukul learning platform.'
    ]
  });
}

const issueCertificate = async (req, res) => {
  try {
    const courseId = Number(req.params.courseId);
    const enrollment = await Enrollment.findOne({
      where: { userId: req.user.id, courseId, status: 'completed' },
      include: [
        { model: Course, as: 'course' },
        { model: User, as: 'user' }
      ]
    });

    if (!enrollment?.course || !enrollment.user) {
      return res.status(400).json({ message: 'Course not fully completed' });
    }

    const existing = await Certificate.findOne({ where: { userId: req.user.id, courseId } });
    if (existing) {
      return res.json(buildCertificatePayload(existing));
    }

    const certificateUid = crypto.randomUUID();
    const certificate = await Certificate.create({
      certificateUid,
      userId: req.user.id,
      courseId,
      enrollmentId: enrollment.id,
      verificationCode: crypto.randomBytes(8).toString('hex').toUpperCase(),
      userNameSnapshot: enrollment.user.name,
      courseTitleSnapshot: enrollment.course.title,
      issuedAt: new Date(),
      certificateUrl: `/api/certificates/${certificateUid}/download`
    });

    await enrollment.update({ certificateIssued: true });

    return res.json(buildCertificatePayload(certificate));
  } catch (err) {
    console.error(err);
    return res.status(500).json({ message: err.message || 'Failed to issue certificate' });
  }
};

const getMyCertificates = async (req, res) => {
  try {
    const certs = await Certificate.findAll({
      where: { userId: req.user.id },
      include: [{ model: Course, as: 'course', attributes: ['id', 'title'] }],
      order: [['issuedAt', 'DESC']]
    });

    return res.json(
      certs.map((certificate) => ({
        ...buildCertificatePayload(certificate),
        course: certificate.course
      }))
    );
  } catch (err) {
    console.error(err);
    return res.status(500).json({ message: 'Failed to load certificates' });
  }
};

const verifyCertificate = async (req, res) => {
  try {
    const cert = await Certificate.findOne({
      where: { certificateUid: req.params.certificateId },
      include: [{ model: Course, as: 'course', attributes: ['id', 'title'] }]
    });

    if (!cert || !cert.isValid) {
      return res.status(404).json({ message: 'Certificate not found or revoked' });
    }

    const verificationCode = req.query.code?.trim();
    if (verificationCode && verificationCode !== cert.verificationCode) {
      return res.status(400).json({ message: 'Invalid verification code' });
    }

    return res.json({
      valid: true,
      certificate: {
        ...buildCertificatePayload(cert),
        course: cert.course
      }
    });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ message: 'Failed to verify certificate' });
  }
};

const downloadCertificate = async (req, res) => {
  try {
    const cert = await Certificate.findOne({
      where: { certificateUid: req.params.certificateId },
      include: [
        { model: Course, as: 'course', attributes: ['id', 'title'] },
        { model: User, as: 'user', attributes: ['id', 'name', 'email'] }
      ]
    });

    if (!cert) {
      return res.status(404).json({ message: 'Certificate not found' });
    }

    const isOwner = Number(cert.userId) === Number(req.user.id);
    if (!isOwner && req.user.role !== 'admin') {
      return res.status(403).json({ message: 'You are not allowed to download this certificate' });
    }

    const pdf = buildCertificatePdf(cert);
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="certificate-${cert.certificateUid}.pdf"`);
    return res.send(pdf);
  } catch (err) {
    console.error(err);
    return res.status(500).json({ message: 'Failed to download certificate' });
  }
};

module.exports = {
  issueCertificate,
  getMyCertificates,
  verifyCertificate,
  downloadCertificate
};
